#!/usr/bin/env python3
"""gen_guess.py — validates guess/tree.json against the profiles manifest and runs the
tree's self-test: every profile answers its own modal answers and the engine must
place it. Writes guess/selftest.json, which the page renders — the numbers about
how many questions the game takes are arithmetic over this run, never typed.

Gates (fail the build): every question carries a p_yes for every profile in the
manifest and no other; every p in [0,1]; every profile is placed by its own modal
answers within the budget.
"""
import json, math, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
tree = json.loads((ROOT / "guess/tree.json").read_text())
idx = json.loads((ROOT / "probes/profiles/index.json").read_text())
P = [p["id"] for p in idx["profiles"]]
prior = {p["id"]: p.get("prior", 0) or 0 for p in idx["profiles"]}
errors = []
for q in tree["questions"]:
    if set(q["p_yes"]) != set(P): errors.append(f"question {q['id']}: p_yes keys {sorted(set(q['p_yes']) ^ set(P))} do not match the manifest")
    for k, v in q["p_yes"].items():
        if not (0 <= v <= 1): errors.append(f"question {q['id']}: p_yes[{k}]={v}")
if abs(sum(prior.values()) - 1) > 0.02: errors.append(f"priors sum to {sum(prior.values()):.2f}, not 1")

S = tree["stop"]; N = tree["noise"]
clip = lambda p: min(N["ceiling"], max(N["floor"], p))
H = lambda b: -sum(v * math.log2(v) for v in b.values() if v > 0)
def norm(b):
    z = sum(b.values()) or 1; return {k: v / z for k, v in b.items()}
def gain(b, q):
    g = H(b)
    for ans in (True, False):
        post = norm({p: b[p] * (clip(q["p_yes"][p]) if ans else 1 - clip(q["p_yes"][p])) for p in P})
        pa = sum(b[p] * (clip(q["p_yes"][p]) if ans else 1 - clip(q["p_yes"][p])) for p in P)
        g -= pa * H(post)
    return g
def play(answer_fn):
    b = norm(dict(prior)); asked = []; path = []
    while len(asked) < S["budget"]:
        lead = max(b, key=b.get)
        if b[lead] >= S["dominant"]: break
        cands = [q for q in tree["questions"] if q["id"] not in asked]
        if not cands: break
        best = max(cands, key=lambda q: gain(b, q))
        if gain(b, best) < S["min_gain"]: break
        a = answer_fn(best)
        asked.append(best["id"])
        if a is not None:
            b = norm({p: b[p] * (clip(best["p_yes"][p]) if a else 1 - clip(best["p_yes"][p])) for p in P})
        path.append((best["id"], a, max(b, key=b.get), round(max(b.values()), 3)))
    lead = max(b, key=b.get)
    return (lead if b[lead] >= S["not_in_set_below"] else None), b[lead], len(asked), path

results = []
for target in P:
    lead, conf, n, path = play(lambda q: q["p_yes"][target] >= 0.5)
    ok = lead == target
    if not ok: errors.append(f"self-test: {target} answered its own modal answers and the tree placed {lead} ({conf:.2f}) after {n} questions")
    results.append({"profile": target, "placed": lead, "correct": ok, "confidence": round(conf, 3), "questions": n, "path": path})
if errors:
    print(f"gen_guess: {len(errors)} GATE FAILURE(S):")
    for e in errors: print("  ✗ " + e)
    sys.exit(1)
out = {"type": "guess-selftest/v1", "_what_this_is": "Each profile answered the tree's questions with its own modal answers (yes where p_yes >= 0.5). Generated by admin/build/gen_guess.py; the page reads it. A self-test is a floor: it shows the tree can tell its own profiles apart, not that it can place a person.",
       "profiles": len(P), "questions_in_tree": len(tree["questions"]),
       "mean_questions": round(sum(r["questions"] for r in results) / len(results), 2),
       "max_questions": max(r["questions"] for r in results),
       "all_placed": all(r["correct"] for r in results), "results": results}
(ROOT / "guess/selftest.json").write_text(json.dumps(out, indent=2) + "\n")
print(f"gen_guess: {len(P)} profiles, {len(tree['questions'])} questions; self-test placed {sum(r['correct'] for r in results)}/{len(P)} in {out['mean_questions']} questions on average (max {out['max_questions']}) -> guess/selftest.json")
