#!/usr/bin/env node
/* people.mjs: the directory of people, on disk. One tool, the same code the pages run (assets/people/).
 *
 *   node admin/build/people.mjs build             read every record, refuse a bad one, write directory/index.json
 *   node admin/build/people.mjs check             the same reading, writing nothing; exit 1 on any problem (validate.js runs it)
 *   node admin/build/people.mjs add <file|->      a submission (pki.sgit.ai/submission/v1, from the vault page, an inbox or an
 *                                                 agent's pki-agent.mjs), or several in one file (pki.sgit.ai/submissions/v1)
 *                                                 verified and written as statement files; then build
 *   node admin/build/people.mjs fixtures          (re)make the fixture cast, private keys published on purpose
 *
 * On disk, in the register's own layout (registry/params.json, record_dirname):
 *   directory/records/sha256-<16 hex>/NN__<type>.json   one signed statement each, never edited, only added
 *   directory/records/sha256-<16 hex>/FIXTURE           present in a fixture record: its private key is published
 *   directory/fixtures/sha256-<16 hex>.json              a fixture's private halves, base64 PKCS#8, published on purpose
 *   directory/anchors.json                               the anchors verification starts from, and the fixture anchor
 *   directory/index.json                                 generated: every record's statements and what was computed
 *
 * The write path is a reviewed commit, as it was for the agent register: `add` cannot put a statement into a record it
 * was not signed for, because the record is checked whole, after the add, before anything is written.
 */
import fs from 'fs'
import path from 'path'

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..')
const DIR = path.join(ROOT, 'directory'), RECORDS = path.join(DIR, 'records'), FIXTURES = path.join(DIR, 'fixtures')
const K = await import(path.join(ROOT, 'assets/people/keys.js'))
const D = await import(path.join(ROOT, 'assets/people/directory.js'))

const readJson = f => JSON.parse(fs.readFileSync(f, 'utf8'))
const writeJson = (f, v) => { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, JSON.stringify(v, null, 2) + '\n') }

async function readAll() {
    const out = []
    if (!fs.existsSync(RECORDS)) return out
    for (const d of fs.readdirSync(RECORDS).sort()) {
        const p = path.join(RECORDS, d)
        if (!fs.statSync(p).isDirectory()) continue
        const files = fs.readdirSync(p).filter(f => /^\d{2,3}__[a-z]+.*\.json$/.test(f)).sort()
        const statements = files.map(f => readJson(path.join(p, f)))
        const r = await D.readRecord(statements, { dir: K.fpOfDir(d), fixture: fs.existsSync(path.join(p, 'FIXTURE')) })
        r.files = files; r.dir = d
        out.push(r)
    }
    return out
}
const anchors = () => fs.existsSync(path.join(DIR, 'anchors.json')) ? readJson(path.join(DIR, 'anchors.json')) : { anchors: [], fixture_anchors: [] }

async function build({ write }) {
    const records = await readAll(), a = anchors()
    const problems = records.flatMap(r => r.problems.map(p => `${r.dir}: ${p}`))
    for (const fp of [...a.anchors, ...a.fixture_anchors]) if (!records.some(r => r.fp === fp)) problems.push(`anchors.json names ${fp}, which has no record`)
    for (const fp of a.anchors) if (records.some(r => r.fp === fp && r.fixture)) problems.push(`anchors.json: ${fp} is a fixture, and a fixture can only be a fixture anchor`)
    const real = D.graph(records, { anchors: a.anchors }), all = D.graph(records, { anchors: [...a.anchors, ...a.fixture_anchors], includeFixtures: true })
    const index = {
        _authority: 'NONE: generated by admin/build/people.mjs from directory/records/; the signed statements are the source, and a reader should check them, not this file',
        v: 1, registry: D.REGISTRY, generated_from: 'directory/records', bounds: D.BOUNDS,
        counts: { real_keys: D.realKeys(records), agent_keys: D.realAgents(records), records: records.length, fixtures: records.filter(r => r.fixture).length, confirmed_links: real.edges.length, confirmed_links_with_fixtures: all.edges.length },
        anchors: a.anchors, fixture_anchors: a.fixture_anchors,
        records: records.map(r => ({ fp: r.fp, dir: r.dir, fixture: r.fixture, ok: r.ok, name: r.name, revoked: r.revoked, statements: r.statements.map(e => e.st) })),
    }
    if (write) writeJson(path.join(DIR, 'index.json'), index)
    return { problems, index }
}

async function add(file) {
    const doc = readJson(file === '-' ? '/dev/stdin' : file)
    const subs = doc && doc.kind === D.SUBMISSIONS && Array.isArray(doc.submissions) ? doc.submissions : [doc]
    for (const sub of subs) await addOne(sub)
}
async function addOne(sub) {
    if (!sub || sub.kind !== D.SUBMISSION || !Array.isArray(sub.statements) || !sub.statements.length) throw new Error('not a pki.sgit.ai submission')
    const fp = sub.statements[0].record
    if (!K.FP.test(String(fp))) throw new Error('the submission names no record')
    const dir = path.join(RECORDS, K.dirOf(fp))
    const have = fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => /^\d+__.*\.json$/.test(f)).sort() : []
    const existing = have.map(f => readJson(path.join(dir, f)))
    const ids = new Set(await Promise.all(existing.map(s => K.statementId(s))))
    const fresh = []
    for (const s of sub.statements) if (!ids.has(await K.statementId(s))) { fresh.push(s); ids.add(await K.statementId(s)) }
    fresh.sort((a, b) => String(a.created_at).localeCompare(String(b.created_at)))
    const r = await D.readRecord([...existing, ...fresh], { dir: fp })
    if (!r.ok) throw new Error(`${fp}: refused, nothing written for it:\n  ${r.problems.join('\n  ')}`)
    let n = have.length
    for (const s of fresh) {
        n++
        const slug = s.type === 'link' ? `__${s.body.method === 'operates' ? 'operates' : 'to'}-${s.body.to.slice(7, 15)}` : s.type === 'evidence' ? `__${s.body.kind}` : ''
        writeJson(path.join(dir, `${String(n).padStart(2, '0')}__${s.type}${slug}.json`), s)
    }
    console.log(`${fp} (${r.name}): ${fresh.length} new statement(s), ${existing.length} already there`)
}

/** The fixture cast: five people who do not exist, and one of them the fixture anchor. Private keys published. */
async function fixtures() {
    const cast = [
        { name: 'Fixture: Ana (the fixture anchor)', about: 'Not a person. The anchor of the fixture graph, so the pages can show verification before a real anchor is in.' },
        { name: 'Fixture: Bruno', about: 'Not a person. Verified by the fixture anchor in person, and linked back.' },
        { name: 'Fixture: Clara', about: 'Not a person. Two steps from the anchor, through Bruno.' },
        { name: 'Fixture: Duarte', about: 'Not a person. Links to Ana, who has not linked back: a claim, and no link.' },
        { name: 'Fixture: Eva', about: 'Not a person. Linked to Clara, then withdrew it.' },
        { name: 'Fixture: Bruno’s research agent', about: 'Not an agent anyone runs. Operated by Bruno, who is verified: the register shows it as his.', agent: { runtime: 'claude-code, cloud session', session: true } },
        { name: 'Fixture: Ana’s fleet', about: 'Not a fleet anyone runs. A fleet key Ana operates, which operates her agents.', agent: { runtime: 'pki.sgit.ai vault' } },
        { name: 'Fixture: an agent of Ana’s fleet', about: 'Not an agent anyone runs. Operated by Ana’s fleet: its page shows Ana at the root.', agent: { runtime: 'a scheduled job' } },
    ]
    fs.rmSync(FIXTURES, { recursive: true, force: true })
    for (const d of fs.existsSync(RECORDS) ? fs.readdirSync(RECORDS) : []) if (fs.existsSync(path.join(RECORDS, d, 'FIXTURE'))) fs.rmSync(path.join(RECORDS, d), { recursive: true })
    const ids = []
    for (const c of cast) ids.push({ ...c, id: await K.generate(c.name.replace('Fixture: ', 'fixture-').split(' ')[0].toLowerCase()) })
    const [ana, bruno, clara, duarte, eva, research, fleet, worker] = ids, fp = x => x.id.bundle.signing_fingerprint
    let t = Date.parse('2026-10-18T09:00:00Z'); const at = () => new Date(t += 60000).toISOString().replace('.000', '')
    const s = {}
    for (const x of ids) s[fp(x)] = [x.agent ? await D.agentStatement(x.id, { ...x, ...x.agent }, at()) : await D.identityStatement(x.id, x, at())]
    const push = async (x, st) => s[fp(x)].push(await st)
    await push(ana, D.evidenceStatement(ana.id, { kind: 'website', value: 'example.org', url: 'https://example.org/.well-known/pki.sgit.ai.txt' }, at()))
    await push(ana, D.linkStatement(ana.id, { to: fp(bruno), method: 'in-person', on: '2026-10-18' }, at()))
    await push(bruno, D.linkStatement(bruno.id, { to: fp(ana), method: 'known' }, at()))
    await push(bruno, D.evidenceStatement(bruno.id, { kind: 'github', value: 'fixture-bruno', url: 'https://gist.github.com/fixture-bruno/0' }, at()))
    await push(bruno, D.linkStatement(bruno.id, { to: fp(clara), method: 'known' }, at()))
    await push(clara, D.linkStatement(clara.id, { to: fp(bruno), method: 'invitation' }, at()))
    await push(duarte, D.linkStatement(duarte.id, { to: fp(ana) }, at()))
    const evaLink = await D.linkStatement(eva.id, { to: fp(clara) }, at())
    await push(eva, evaLink)
    await push(clara, D.linkStatement(clara.id, { to: fp(eva) }, at()))
    await push(eva, D.withdrawStatement(eva.id, evaLink, 'withdrawn', at()))
    await push(research, D.linkStatement(research.id, { to: fp(bruno), method: 'operated-by' }, at()))
    await push(bruno, D.linkStatement(bruno.id, { to: fp(research), method: 'operates', on: '2026-10-18', until: '2027-04-18' }, at()))
    await push(fleet, D.linkStatement(fleet.id, { to: fp(ana), method: 'operated-by' }, at()))
    await push(ana, D.linkStatement(ana.id, { to: fp(fleet), method: 'operates', on: '2026-10-18', until: '2027-10-18' }, at()))
    await push(worker, D.linkStatement(worker.id, { to: fp(fleet), method: 'operated-by' }, at()))
    await push(fleet, D.linkStatement(fleet.id, { to: fp(worker), method: 'operates', on: '2026-10-18', until: '2027-04-18' }, at()))
    for (const x of ids) {
        const dir = path.join(RECORDS, K.dirOf(fp(x)))
        fs.mkdirSync(dir, { recursive: true })
        fs.writeFileSync(path.join(dir, 'FIXTURE'), 'This record is a fixture: its private keys are published in directory/fixtures/. Nothing it signs proves anything.\n')
        s[fp(x)].forEach((st, i) => writeJson(path.join(dir, `${String(i + 1).padStart(2, '0')}__${st.type}.json`), st))
        writeJson(path.join(FIXTURES, `${K.dirOf(fp(x))}.json`), { _warning: 'FIXTURE: these private keys are published on purpose. Nothing signed with them proves anything about anyone.',
            name: x.name, bundle: x.id.bundle, private: { encrypt: K.b64(x.id.private.encrypt), sign: K.b64(x.id.private.sign) } })
    }
    const a = anchors(); a.fixture_anchors = [fp(ana)]
    writeJson(path.join(DIR, 'anchors.json'), { _note: 'anchors: the keys verification starts from in the real register (Dinis Cruz, once his key is in). fixture_anchors: the same, for the fixture graph only.', anchors: a.anchors || [], fixture_anchors: a.fixture_anchors })
    console.log('fixtures:', ids.map(x => `${x.name} ${fp(x)}`).join('\n  '))
}

const [cmd, arg] = process.argv.slice(2)
try {
    if (cmd === 'fixtures') { await fixtures(); await build({ write: true }) }
    else if (cmd === 'add') { if (!arg) throw new Error('add <file|->'); await add(arg); const { problems } = await build({ write: true }); if (problems.length) throw new Error(problems.join('\n')) }
    else if (cmd === 'build' || cmd === 'check') {
        const { problems, index } = await build({ write: cmd === 'build' })
        if (cmd === 'check' && fs.existsSync(path.join(DIR, 'index.json'))) {
            const onDisk = readJson(path.join(DIR, 'index.json'))
            if (JSON.stringify(onDisk) !== JSON.stringify(index)) problems.push('directory/index.json is stale: run node admin/build/people.mjs build')
        }
        if (problems.length) { console.error(problems.map(p => 'directory: ' + p).join('\n')); process.exit(1) }
        console.log(`directory: ${index.counts.records} records, ${index.counts.real_keys} real key(s), ${index.counts.fixtures} fixtures, ${index.counts.confirmed_links_with_fixtures} confirmed link(s)`)
    } else { console.error('usage: people.mjs build | check | add <file|-> | fixtures'); process.exit(2) }
} catch (e) { console.error(String(e && e.message || e)); process.exit(1) }
