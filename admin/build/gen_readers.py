#!/usr/bin/env python3
"""Generates the synthetic-readers area under packs/map-your-case/readers/.

Run from anywhere: python3 admin/build/gen_readers.py, then admin/build/chrome.py.

This area holds SIMULATED material, so it is generated by its own script, lives in
its own directory, and renders differently from every other page on this site —
rule one: a simulated reaction must never be confusable with a real one. The
marker is applied here in four places at once (filename, banner, running header,
and beside every quote) so that no crop, screenshot or copy-paste of a run record
loses it.

Data: packs/map-your-case/readers/readers.json. Prose: the .md files beside it.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / "packs" / "map-your-case" / "readers"
GH = "https://github.com/SGit-AI/SGit-AI__Website__PKI"
UP = "../../../"

NAV_STUB = '<nav class="site"><div class="row"></div></nav>'
FOOT_STUB = '<footer class="site"><div class="cols"></div></footer>'
READER_TAIL = f'''
<script src="https://cdn.jsdelivr.net/npm/marked@12/marked.min.js"></script>
<script src="{UP}assets/mdreader.js"></script>'''

SIM_RAIL = '<div class="simrail">Simulated readers · not real users · every reaction below was generated</div>'


def head(title, desc, canonical):
    return f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{title}</title>
<meta name="description" content="{desc}">
<link rel="canonical" href="https://pki.sgit.ai/{canonical}">
<link rel="stylesheet" href="{UP}assets/site.css">
<link rel="stylesheet" href="readers.css">
</head>
<body>

{NAV_STUB}
'''


def crumb(tail):
    return (f'<div class="crumb"><a href="{UP}index.html">pki.sgit.ai</a> / '
            f'<a href="{UP}packs/index.html">packs</a> / '
            f'<a href="../index.html">map-your-case</a> / {tail}</div>')


def mdpage(slug, title, desc, lead, src, tailnav, sim=False):
    simhead = (SIM_RAIL + '''
<main class="doc">''') if sim else '<main class="doc">'
    simnote = ('''<div class="simbanner"><b>This page reads a simulated run.</b> Every reader quotation it
contains was generated by a language model playing an archetype — <b>no person said any of it</b> — and
every conclusion drawn here inherits that limit.</div>''') if sim else ''
    body = head(f'{title} · synthetic readers · pki.sgit.ai', desc, f'packs/map-your-case/readers/{slug}.html') + f'''
{simhead}
{crumb(f'<a href="index.html">readers</a> / {slug}')}
<h1>{title}</h1>
<p class="lead">{lead}</p>
{simnote}

<div class="mdread-label">📄 {src} · rendered from the <a href="{src}">raw markdown</a> (the source of truth)</div>
<div class="mdread" id="mdread" data-src="{src}"><noscript><p class="dim">In-page rendering needs JavaScript — <a href="{src}">open the raw markdown</a>.</p></noscript></div>

<div class="pagenav">
{tailnav}
</div>
</main>

{FOOT_STUB}
{READER_TAIL}
</body>
</html>
'''
    (BASE / f"{slug}.html").write_text(body)


def run_page(d, r):
    arch = next(a for a in d["archetypes"] if a["id"] == r["archetype"])
    slug = f'simulated-run-{r["id"]}-{r["slug"]}'
    steps = []
    for s in r["steps"]:
        note = f'<p class="rnote"><b>Renderer note.</b> {s["note"]}</p>' if s.get("note") else ""
        act = (f'<div class="qa"><p class="q">The reader\'s next move, in their words</p>'
               f'<span class="act">{s["action"]}</span></div>') if s.get("action") else ""
        closing = (f'<div class="qa"><p class="q">Closing question — now that you have seen it: what do you '
                   f'think of what you saw, and what will you do differently?</p>'
                   f'<blockquote class="simquote">{s["closing"]}</blockquote></div>') if s.get("closing") else ""
        steps.append(f'''
<section class="step">
  <h3><span class="n">Screen {s["n"]} of {r["budget"]["screens"]}</span> · {s["caption"]}</h3>
  <figure class="shotwrap">
    <img src="shots/{s["shot"]}" alt="Simulated run {r["id"]}, screen {s["n"]}: {s["caption"]}" loading="lazy">
    <figcaption>What the reader was given — the whole of what it knew at this point. Nothing else was passed to it: no text, no structure, no page source.</figcaption>
  </figure>
  <div class="react">
    <div class="qa"><p class="q">Comprehension question — what would you do now, and what did that page tell you?</p>
      <blockquote class="simquote">{s["comprehension"]}</blockquote></div>
    {act}
    {closing}
    {note}
  </div>
</section>''')

    findings = "\n".join(
        f'    <tr><td>{f["id"]}</td><td>{f["what"]}</td><td>{f["evidence"]}</td><td>{f["status"]}</td></tr>'
        for f in r["findings"])

    page = head(f'Simulated run {r["id"]} — {arch["label"]} · pki.sgit.ai',
                f'A simulated synthetic-reader run against the assessment page: {arch["label"]}, {r["arrival"]} arrival, budget {r["budget"]["screens"]} screens. Every reaction was generated, not collected from a person.',
                f'packs/map-your-case/readers/{slug}.html') + f'''
{SIM_RAIL}
<main class="doc">
{crumb(f'<a href="index.html">readers</a> / run {r["id"]}')}
<h1>Simulated run {r["id"]} — {arch["label"]}</h1>

<div class="simbanner"><b>This is a simulated run.</b> Every reaction on this page was produced by a
language model playing an archetype — <b>no person said any of it</b>, and none of it is user
research. It is published because the runs that change a design are evidence of a working method,
and a method whose failures are unpublished is marketing. Quotes carry the marker individually so
that no fragment of this page can be lifted and passed off as a real user's words.</div>

<div class="docmeta">
  <span class="k">Archetype</span><span class="v">{arch["id"]} — {arch["label"]} <span class="dim">({arch["position"]})</span></span>
  <span class="k">Run type</span><span class="v">{r["type_label"]}</span>
  <span class="k">Arrival</span><span class="v">{r["arrival_label"]}</span>
  <span class="k">Artefact</span><span class="v">{r["artefact"]}</span>
  <span class="k">Date</span><span class="v">{r["date"]}</span>
  <span class="k">Reader knew</span><span class="v">{r["knew"]}</span>
</div>

<h2 id="ledger">The budget ledger</h2>
<p>Set before the run, spent by mechanical rule. The reader never managed its own patience — that is
what makes an abandonment a measurement rather than a story.</p>
<div class="ledger">
  <div><span class="k">Screens</span><span class="v">{r["spend"]["screens"]} of {r["budget"]["screens"]}</span></div>
  <div><span class="k">Clicks</span><span class="v">{r["spend"]["clicks"]} of {r["budget"]["clicks"]}</span></div>
  <div><span class="k">Minutes (est.)</span><span class="v">{r["spend"]["minutes"]} of {r["budget"]["minutes"]}</span></div>
  <div><span class="k">Outcome</span><span class="v">{r["spend"]["outcome"]}</span></div>
</div>

<h2 id="expectation">Before the first screenshot</h2>
<p>The reader was given the fixed <a href="instruments.html">elevator pitch</a> and nothing else, then
asked what it expected. This half of the measurement is taken before the page can influence it.</p>
<div class="qa"><p class="q">Expectation question — what do you expect this page to show you, and what would make it worth your time?</p>
<blockquote class="simquote">{r["expectation"]}</blockquote></div>

<h2 id="run">The run</h2>
{"".join(steps)}

<h2 id="findings">What the run found</h2>
<div class="tablewrap"><table class="fnd">
  <thead><tr><th>#</th><th>Finding</th><th>Evidence</th><th>Status</th></tr></thead>
  <tbody>
{findings}
  </tbody>
</table></div>

<h2 id="reading">Reading it honestly</h2>
{r["honest"]}

<div class="pagenav">
  <a href="index.html">← The readers area</a>
  <a href="{r["analysis"].replace(".md", ".html")}">The informed analysis →</a>
</div>
</main>

{FOOT_STUB}

</body>
</html>
'''
    (BASE / f"{slug}.html").write_text(page)
    return slug


def hub(d):
    runrows = "\n".join(
        f'    <tr><td><a href="simulated-run-{r["id"]}-{r["slug"]}.html"><b>Run {r["id"]}</b></a></td>'
        f'<td>{next(a for a in d["archetypes"] if a["id"] == r["archetype"])["label"]}</td>'
        f'<td>{r["type_label"]}</td><td>{r["arrival_label"]}</td>'
        f'<td>{r["spend"]["outcome"]}</td></tr>'
        for r in d["runs"])
    planned = "\n".join(
        f'    <tr><td class="dim">{p["id"]}</td><td>{p["archetype_label"]}</td><td>{p["type_label"]}</td>'
        f'<td>{p["arrival_label"]}</td><td class="dim">{p["status"]}</td></tr>'
        for p in d["planned"])
    cards = "\n".join(
        f'''<div class="arch">
  <h3><span class="code">{a["id"]}</span> — {a["label"]}</h3>
  <p>{a["blurb"]}</p>
  <dl>
    <dt>Grant position</dt><dd>{a["position"]}</dd>
    <dt>Prior confidence</dt><dd>{a["confidence"]}</dd>
    <dt>Predicted failure</dt><dd>{a["predicted"]}</dd>
  </dl>
</div>''' for a in d["archetypes"])
    findrows = "\n".join(
        f'    <tr><td>{f["id"]}</td><td>{f["what"]}</td><td>{f["run"]}</td><td>{f["status"]}</td></tr>'
        for f in d["findings"])

    page = head("Synthetic readers · Map Your Case · pki.sgit.ai",
                "The synthetic-readers programme: three archetypes, a pixels-only reader agent, exogenous patience budgets, and published run records including the runs that failed.",
                "packs/map-your-case/readers/index.html") + f'''
<main class="doc">
{crumb("readers")}
<h1>Synthetic readers</h1>
<p class="lead">The instrument that tests the pages, kept deliberately outside <a href="../index.html">the pack</a>
because it <b>feeds</b> the pack rather than belonging to it. Two agents: one is a browser and nothing else, one
is an archetype that receives <b>pixels and nothing else</b> and points at where to go next. Patience is set from
outside the model, so abandonment is a measured event rather than a story. Findings flow one way — into the pack's
<a href="../change-control.html">change control</a>.</p>

<div class="simbanner"><b>Everything in the run records is simulated.</b> No person said any of it. Synthetic
readers reliably find <b>defects</b> — a page that does not answer its own question, a term used before it is
defined, a dead end — and cannot report <b>preferences</b>. Those need people, and no person has yet run this
protocol, so there is no calibration record and nothing here is known to predict what a human would do.</div>

<h2 id="archetypes">The three archetypes</h2>
<p>Property lists, not portraits — composed so that they map to no individual, with the sources recorded nowhere.
The full definitions are in <a href="archetypes.html">the archetypes document</a>.</p>
{cards}

<h2 id="runs">Runs performed</h2>
<div class="tablewrap"><table>
  <thead><tr><th>Run</th><th>Archetype</th><th>Type</th><th>Arrival</th><th>Outcome</th></tr></thead>
  <tbody>
{runrows}
  </tbody>
</table></div>

<h2 id="schedule">Scheduled, and not yet run</h2>
<p>Published as a schedule rather than as results, so that what has <em>not</em> been done is as visible as what has.</p>
<div class="tablewrap"><table>
  <thead><tr><th>Run</th><th>Archetype</th><th>Type</th><th>Arrival</th><th>Status</th></tr></thead>
  <tbody>
{planned}
  </tbody>
</table></div>

<h2 id="findings">Findings so far</h2>
<div class="tablewrap"><table class="fnd">
  <thead><tr><th>#</th><th>Finding</th><th>From</th><th>Status</th></tr></thead>
  <tbody>
{findrows}
  </tbody>
</table></div>

<h2 id="programme">The programme</h2>
<div class="mdread-label">📄 programme.md · rendered from the <a href="programme.md">raw markdown</a> (the source of truth)</div>
<div class="mdread" id="mdread" data-src="programme.md"><noscript><p class="dim">In-page rendering needs JavaScript — <a href="programme.md">open the raw markdown</a>.</p></noscript></div>

<div class="pagenav">
  <a href="../index.html">← The pack</a>
  <a href="archetypes.html">The archetypes →</a>
</div>
</main>

{FOOT_STUB}
{READER_TAIL}
</body>
</html>
'''
    (BASE / "index.html").write_text(page)


def main():
    d = json.loads((BASE / "readers.json").read_text())
    hub(d)
    mdpage("archetypes", "The three archetypes",
           "Three synthetic-reader archetypes as property lists rather than portraits: the shipping founder, the agent-security practitioner, the adoption executive.",
           "Property lists, composed so that each maps to no individual. The property list <b>is</b> the archetype — which is also what makes it useful, because the parameters can be varied independently and a portrait cannot be.",
           "archetypes.md",
           '<a href="index.html">← The readers area</a>\n  <a href="instruments.html">The instruments →</a>')
    mdpage("instruments", "The fixed instruments",
           "The elevator pitch, the expectation question, the comprehension question and the closing question — fixed wording, because a varying question produces varying answers that look like findings.",
           "Four pieces of fixed wording. Changing any of them is a change-control entry rather than an edit — a varying question produces varying answers that look like findings.",
           "instruments.md",
           '<a href="archetypes.html">← The archetypes</a>\n  <a href="index.html">The readers area →</a>')
    n = 2
    for r in d["runs"]:
        slug = run_page(d, r)
        n += 1
        if r.get("analysis"):
            mdpage(r["analysis"][:-3], f'Informed analysis — run {r["id"]}',
                   f'The second-pass analysis of simulated run {r["id"]}: what worked, what did not, what the tool is worth to this archetype, and what should change.',
                   'The <b>type B</b> pass: an agent that <em>has</em> read the pack, looking at the same run. Kept separate from the tabletop, and always after it — an agent that both reacts and analyses produces a reaction shaped by what it is about to conclude.',
                   r["analysis"],
                   f'<a href="{slug}.html">← The run record</a>\n  <a href="index.html">The readers area →</a>',
                   sim=True)
            n += 1
    print(f"gen_readers: {n + 1} page(s) written under packs/map-your-case/readers/")


if __name__ == "__main__":
    main()
